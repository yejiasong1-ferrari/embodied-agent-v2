from dataclasses import dataclass
from typing import Callable, Protocol
import numpy as np


@dataclass(frozen=True)
class Pose:
    position: np.ndarray
    rotation: np.ndarray


@dataclass(frozen=True)
class ContactState:
    left_force: float = 0
    right_force: float = 0
    unexpected: bool = False
    @property
    def bilateral(self): return self.left_force > .1 and self.right_force > .1


class RobotInterface(Protocol):
    joint_limits: tuple[np.ndarray, np.ndarray]
    def get_joint_positions(self) -> np.ndarray: ...
    def get_ee_pose(self) -> Pose: ...
    def move_joint(self, joints, monitor: Callable | None = None) -> bool: ...
    def move_cartesian(self, pose: Pose, monitor: Callable | None = None) -> bool: ...
    def execute_trajectory(self, positions, times, monitor: Callable | None = None) -> bool: ...
    def open_gripper(self, monitor: Callable | None = None) -> bool: ...
    def close_gripper(self, width: float, monitor: Callable | None = None, target_force_n: float | None = None) -> bool: ...
    def get_gripper_state(self) -> dict: ...
    def get_contact_state(self) -> ContactState: ...
    def stop(self) -> None: ...
    def resume(self) -> None: ...
    def hold(self, duration: float, monitor: Callable | None = None) -> bool: ...
    def solve_ik(self, pose: Pose, seed: np.ndarray) -> list[np.ndarray]: ...
    def forward_kinematics(self, joints) -> Pose: ...
    def configure_collision_world(self, world, target_id=None, payload=None, support_id=None) -> None: ...
    def check_collision(self, joints) -> str | None: ...


class PolicyInterface(Protocol):
    """Optional learned skill policy. Its actions still pass the local planner."""
    def propose(self, observation: dict, skill: str) -> dict: ...
